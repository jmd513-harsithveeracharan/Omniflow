"""
app/fabric_compiler.py
----------------------
Compiles Fabric item definitions into Base64-encoded multi-part payloads
ready for POST /updateDefinition or POST /items creation.
"""

from __future__ import annotations

import base64
import json
import uuid
from typing import Any


def _b64(content: str) -> str:
    """Encodes a UTF-8 string to a Base64 string."""
    return base64.b64encode(content.encode("utf-8")).decode("utf-8")


def _platform_part(item_type: str, display_name: str, logical_id: str | None = None) -> dict[str, Any]:
    """Builds the standard .platform definition part."""
    logical_id = logical_id or str(uuid.uuid4())
    platform = {
        "$schema": "https://developer.microsoft.com/json-schemas/fabric/gitIntegration/platformProperties/2.0.0/schema.json",
        "metadata": {"type": item_type, "displayName": display_name},
        "config": {"version": "2.0", "logicalId": logical_id},
    }
    return {"path": ".platform", "payload": _b64(json.dumps(platform)), "payloadType": "InlineBase64"}


def _metadata_part(item_type: str, display_name: str) -> dict[str, Any]:
    """Builds the item.metadata.json definition part."""
    metadata = {"type": item_type, "displayName": display_name}
    return {"path": "item.metadata.json", "payload": _b64(json.dumps(metadata)), "payloadType": "InlineBase64"}


def _wrap_notebook_content(pyspark_code: str, display_name: str) -> str:
    """Wraps raw PySpark code in Fabric's standard notebook-content.py format."""
    return f"""# Fabric notebook source\n\n# METADATA ********************\n# META {{"kernel_info": {{"name": "synapse_pyspark"}}, "dependencies": {{}}}}\n\n# MARKDOWN ********************\n# # {display_name}\n# Auto-generated by Fabric AI Studio\n\n# CELL ********************\n{pyspark_code}\n\n# METADATA ********************\n# META {{"language": "python", "language_group": "synapse_pyspark"}}\n"""


# ── Core Items ──────────────────────────────────────────────────────────────

def compile_lakehouse(name: str) -> dict[str, Any]:
    """Returns the item creation payload for a Fabric Lakehouse."""
    return {
        "displayName": name,
        "type": "Lakehouse",
        "description": f"AI-provisioned Lakehouse ({name})",
        "definition": {"parts": [_metadata_part("Lakehouse", name), _platform_part("Lakehouse", name)]},
    }


def compile_notebook(name: str, pyspark_code: str) -> dict[str, Any]:
    """Returns the item creation payload for a Fabric Notebook."""
    nb_content = _wrap_notebook_content(pyspark_code, name)
    return {
        "displayName": name,
        "type": "Notebook",
        "description": f"AI-generated PySpark Notebook ({name})",
        "definition": {
            "parts": [
                {"path": "notebook-content.py", "payload": _b64(nb_content), "payloadType": "InlineBase64"},
                _metadata_part("Notebook", name),
                _platform_part("Notebook", name),
            ]
        },
    }


def compile_notebook_update(pyspark_code: str, display_name: str) -> list[dict[str, Any]]:
    """Returns definition parts for notebook updateDefinition."""
    nb_content = _wrap_notebook_content(pyspark_code, display_name)
    return [{"path": "notebook-content.py", "payload": _b64(nb_content), "payloadType": "InlineBase64"}]


def compile_pipeline(
    name: str, notebook_ids: list[str], workspace_id: str, schedule_cron: str | None = None
) -> tuple[dict[str, Any], list[dict[str, Any]]]:
    """Returns (create_payload, update_parts) for a Data Factory pipeline."""
    from app.generators.pipeline_gen import generate_pipeline_activity_dag, package_pipeline_definition_parts
    activities = generate_pipeline_activity_dag(notebook_ids, workspace_id)
    parts = package_pipeline_definition_parts(activities, schedule_cron=schedule_cron)
    parts.append(_platform_part("DataPipeline", name))
    create_payload = {"displayName": name, "type": "DataPipeline", "description": "AI-orchestrated pipeline"}
    return create_payload, parts


def compile_environment(name: str, extra_packages: list[str] | None = None) -> dict[str, Any]:
    """Returns the item creation payload for a Fabric Spark Environment."""
    from app.generators.environment_gen import generate_environment_conda_yaml, package_environment_definition_parts
    conda_yaml = generate_environment_conda_yaml(environment_name=name, extra_pip_packages=extra_packages)
    parts = package_environment_definition_parts(conda_yaml)
    parts.extend([_metadata_part("Environment", name), _platform_part("Environment", name)])
    return {"displayName": name, "type": "Environment", "description": f"Environment ({name})", "definition": {"parts": parts}}


