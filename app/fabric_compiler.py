"""
app/fabric_compiler.py
----------------------
Compiles Fabric item definitions into Base64-encoded multi-part payloads
ready for POST /updateDefinition.

Replaces the FabricItemGenerator class in fabric_ai_engine.py with
clean, testable, standalone functions.
"""

import json
import base64
import uuid


def _b64(content: str) -> str:
    """Encodes a UTF-8 string to a Base64 string."""
    return base64.b64encode(content.encode("utf-8")).decode("utf-8")


def _platform_part(item_type: str, display_name: str, logical_id: str | None = None) -> dict:
    """Builds the standard .platform definition part."""
    logical_id = logical_id or str(uuid.uuid4())
    platform = {
        "$schema": "https://developer.microsoft.com/json-schemas/fabric/gitIntegration/platformProperties/2.0.0/schema.json",
        "metadata": {"type": item_type, "displayName": display_name},
        "config": {"version": "2.0", "logicalId": logical_id},
    }
    return {"path": ".platform", "payload": _b64(json.dumps(platform)), "payloadType": "InlineBase64"}


def _metadata_part(item_type: str, display_name: str) -> dict:
    """Builds the item.metadata.json definition part."""
    metadata = {"type": item_type, "displayName": display_name}
    return {"path": "item.metadata.json", "payload": _b64(json.dumps(metadata)), "payloadType": "InlineBase64"}


# ── Lakehouse ─────────────────────────────────────────────────────────────────

def compile_lakehouse(name: str) -> dict:
    """Returns the full item creation payload for a Fabric Lakehouse."""
    return {
        "displayName": name,
        "type": "Lakehouse",
        "description": f"AI-provisioned Lakehouse ({name})",
        "definition": {
            "parts": [
                _metadata_part("Lakehouse", name),
                _platform_part("Lakehouse", name),
            ]
        },
    }


# ── Notebook ──────────────────────────────────────────────────────────────────

def _wrap_notebook_content(pyspark_code: str, display_name: str) -> str:
    """Wraps raw PySpark code in Fabric's standard notebook-content.py format."""
    return f"""# Fabric notebook source

# METADATA ********************

# META {{
# META   "kernel_info": {{
# META     "name": "synapse_pyspark"
# META   }},
# META   "dependencies": {{}}
# META }}

# CELL ********************

# MARKDOWN ********************

# # {display_name}
# Auto-generated by Fabric AI Studio

# CELL ********************

{pyspark_code}

# METADATA ********************

# META {{
# META   "language": "python",
# META   "language_group": "synapse_pyspark"
# META }}
"""


def compile_notebook(name: str, pyspark_code: str) -> dict:
    """Returns the full item creation payload for a Fabric Notebook."""
    nb_content = _wrap_notebook_content(pyspark_code, name)
    return {
        "displayName": name,
        "type": "Notebook",
        "description": f"AI-generated PySpark Notebook ({name})",
        "definition": {
            "parts": [
                {"path": "notebook-content.py", "payload": _b64(nb_content), "payloadType": "InlineBase64"},
                _metadata_part("Notebook", name),
                _platform_part("Notebook", name),
            ]
        },
    }


def compile_notebook_update(pyspark_code: str, display_name: str) -> list[dict]:
    """
    Returns just the definition parts for updateDefinition (not a create payload).
    Used when patching an existing notebook during self-healing.
    """
    nb_content = _wrap_notebook_content(pyspark_code, display_name)
    return [
        {"path": "notebook-content.py", "payload": _b64(nb_content), "payloadType": "InlineBase64"},
    ]


# ── Data Pipeline ─────────────────────────────────────────────────────────────

def compile_pipeline(
    name: str,
    notebook_ids: list[str],
    workspace_id: str,
    schedule_cron: str | None = None,
    end_time: str | None = None,
) -> tuple[dict, list[dict]]:
    """
    Returns (create_payload, update_parts) for a Data Factory pipeline.

    create_payload — used for POST /items to create the pipeline item.
    update_parts   — used for POST /updateDefinition to upload the activity graph.
    """
    activities = []
    for i, nb_id in enumerate(notebook_ids):
        activity = {
            "name": f"Run_Notebook_{i + 1}",
            "type": "TridentNotebook",
            "typeProperties": {
                "notebookId": nb_id,
                "workspaceId": workspace_id,
            },
        }
        if i > 0:
            activity["dependsOn"] = [
                {"activity": f"Run_Notebook_{i}", "dependencyConditions": ["Succeeded"]}
            ]
        activities.append(activity)

    pipeline_content: dict = {"properties": {"activities": activities}}

    if schedule_cron:
        cron_str = schedule_cron.strip()
        cron_parts = cron_str.split()
        minute = int(cron_parts[0]) if len(cron_parts) > 0 and cron_parts[0].isdigit() else 0
        hour = int(cron_parts[1]) if len(cron_parts) > 1 and cron_parts[1].isdigit() else 2
        is_hourly = len(cron_parts) > 1 and cron_parts[1] == "*"

        # 1. Native Fabric Schedules Array
        pipeline_content["properties"]["schedules"] = [
            {
                "name": "Pipeline_Cron_Schedule",
                "type": "Cron",
                "cronExpression": cron_str,
                "timeZone": "UTC",
                "enabled": True,
            }
        ]

        # 2. Fabric Triggers Definition (with optional expiration endTime)
        recurrence_def: dict = {
            "frequency": "Hour" if is_hourly else "Day",
            "interval": 1,
            "startTime": "2026-01-01T00:00:00Z",
            "timeZone": "UTC",
            "schedule": {
                "hours": [hour] if not is_hourly else list(range(24)),
                "minutes": [minute],
            },
        }
        if end_time:
            recurrence_def["endTime"] = end_time

        pipeline_content["properties"]["triggers"] = [
            {
                "name": "DailyScheduleTrigger" if not is_hourly else "HourlyScheduleTrigger",
                "type": "ScheduleTrigger",
                "typeProperties": {
                    "recurrence": recurrence_def
                },
            }
        ]

        # 3. Properties Level Schedule Spec
        pipeline_content["properties"]["schedule"] = {
            "type": "ScheduleTrigger",
            "recurrence": {"frequency": "Hour" if is_hourly else "Day", "interval": 1},
            "cronExpression": cron_str,
        }

    logical_id = str(uuid.uuid4())
    platform = {
        "$schema": "https://developer.microsoft.com/json-schemas/fabric/gitIntegration/platformProperties/2.0.0/schema.json",
        "metadata": {
            "type": "DataPipeline",
            "displayName": name,
            "description": "AI-orchestrated ingestion pipeline",
        },
        "config": {"version": "2.0", "logicalId": logical_id},
    }

    update_parts = [
        {"path": "pipeline-content.json", "payload": _b64(json.dumps(pipeline_content)), "payloadType": "InlineBase64"},
        {"path": ".platform", "payload": _b64(json.dumps(platform)), "payloadType": "InlineBase64"},
    ]

    create_payload = {
        "displayName": name,
        "type": "DataPipeline",
        "description": "AI-orchestrated ingestion pipeline",
    }

    return create_payload, update_parts


# ── Spark Environment ─────────────────────────────────────────────────────────

def compile_environment(name: str, extra_packages: list[str] | None = None) -> dict:
    """Returns the item creation payload for a Fabric Spark Environment."""
    base_packages = ["delta-spark>=3.0.0", "pandas>=2.0.0"]
    packages = base_packages + (extra_packages or [])

    env_yaml = "name: fabric_ai_env\nchannels:\n  - conda-forge\ndependencies:\n  - python=3.10\n  - pip:\n"
    for pkg in packages:
        env_yaml += f"    - {pkg}\n"

    return {
        "displayName": name,
        "type": "Environment",
        "description": f"AI-configured PySpark environment ({name})",
        "definition": {
            "parts": [
                {"path": "environment.yml", "payload": _b64(env_yaml), "payloadType": "InlineBase64"},
                _metadata_part("Environment", name),
                _platform_part("Environment", name),
            ]
        },
    }
