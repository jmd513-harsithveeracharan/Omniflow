"""
app/generators/kql_queryset_gen.py
----------------------------------
Generates Microsoft Fabric KQL Queryset definition parts (.kql query files and
database association metadata) for Synapse Real-Time Analytics.
"""

from __future__ import annotations

import base64
import json
from typing import Any
from pydantic import BaseModel


class KQLQuery(BaseModel):
    title: str
    description: str = ""
    query_text: str


def _b64(content: str) -> str:
    """Encodes a UTF-8 string to Base64."""
    return base64.b64encode(content.encode("utf-8")).decode("utf-8")


def generate_kql_queryset_script(
    queryset_name: str,
    target_kql_database: str,
    table_names: list[str] | None = None,
    custom_queries: list[dict[str, str]] | None = None,
) -> str:
    """Generates an operational KQL analytical script with time-series and anomaly queries."""
    tables = table_names or ["TelemetryEvents", "SystemLogs"]
    primary_tbl = tables[0]

    lines: list[str] = [
        f"// ===========================================================================",
        f"// Microsoft Fabric KQL Queryset: {queryset_name}",
        f"// Target KQL Database: {target_kql_database}",
        f"// Generated by Fabric AI Studio",
        f"// ===========================================================================",
        "",
        f"// --- 1. Basic Health & Row Ingestion Rate ---",
        f"{primary_tbl}",
        f"| where Timestamp > ago(24h)",
        f"| summarize TotalEvents = count(), MinTime = min(Timestamp), MaxTime = max(Timestamp)",
        "",
        f"// --- 2. 1-Hour Time-Bucket Aggregations ---",
        f"{primary_tbl}",
        f"| where Timestamp > ago(7d)",
        f"| summarize EventCount = count() by bin(Timestamp, 1h)",
        f"| render timechart with (title = 'Event Ingestion Velocity over 7 Days')",
        "",
        f"// --- 3. Machine Learning Anomaly Detection (series_decompose_anomalies) ---",
        f"let startTime = ago(14d);",
        f"let endTime = now();",
        f"{primary_tbl}",
        f"| where Timestamp between (startTime .. endTime)",
        f"| make-series ActualEvents = count() default=0 on Timestamp from startTime to endTime step 1h",
        f"| extend (Anomalies, Score, Baseline) = series_decompose_anomalies(ActualEvents, 1.5, -1, 'linefit')",
        f"| render anomalychart with (anomalycolumns=Anomalies, title='Real-Time Anomaly Detection')",
        "",
    ]

    if custom_queries:
        lines.append("// --- Custom Domain Queries ---")
        for q in custom_queries:
            title = q.get("title", "Custom Query")
            q_code = q.get("query", f"{primary_tbl} | take 100")
            lines.extend([f"// {title}", q_code, ""])

    return "\n".join(lines)


def package_kql_queryset_definition_parts(
    queryset_name: str,
    kql_script: str,
    kql_database_id: str | None = None,
    kql_database_name: str | None = None,
) -> list[dict[str, Any]]:
    """Packages KQL Queryset parts into Base64 payload for Fabric REST API."""
    metadata = {
        "format": "KqlQueryset",
        "databaseReference": {
            "databaseId": kql_database_id or "00000000-0000-0000-0000-000000000000",
            "databaseName": kql_database_name or "KQLDatabase",
        },
    }

    return [
        {
            "path": "queryset.kql",
            "payload": _b64(kql_script),
            "payloadType": "InlineBase64",
        },
        {
            "path": "queryset.json",
            "payload": _b64(json.dumps(metadata, indent=2)),
            "payloadType": "InlineBase64",
        },
    ]
