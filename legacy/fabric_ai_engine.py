# --- API DEPLOYMENT ENGINE ---

def deploy_item_to_workspace(item_payload: dict, workspace_id: str = ALLOWED_WORKSPACE_ID):
    # Enforce security lock
    assert_workspace_security(workspace_id)
    
    token = get_fabric_token()
    if not token:
        return {"success": False, "error": "Authentication token invalid. Run 'az login'."}

    url = f"https://api.fabric.microsoft.com/v1/workspaces/{workspace_id}/items"
    headers = {
        "Authorization": f"Bearer {token}",
        "Content-Type": "application/json"
    }

    item_name = item_payload.get("displayName")
    item_type = item_payload.get("type")
    print(f"[DEPLOY] Deploying {item_type} '{item_name}' to workspace PBT_DATA_AGENT ({workspace_id})...")

    try:
        res = requests.post(url, headers=headers, json=item_payload)
        if res.status_code in [200, 201, 202]:
            data = res.json() if res.text else {}
            item_id = data.get("id", "Async_Creation")
            print(f"[SUCCESS] {item_type} '{item_name}' deployed successfully! Item ID: {item_id}")
            return {"success": True, "itemId": item_id, "statusCode": res.status_code, "name": item_name, "type": item_type}
        else:
            print(f"[ERROR] Deployment failed ({res.status_code}): {res.text}")
            return {"success": False, "statusCode": res.status_code, "error": res.text, "name": item_name}
    except Exception as e:
        return {"success": False, "error": str(e), "name": item_name}

def list_workspace_items():
    """Audits workspace items inside PBT_DATA_AGENT."""
    token = get_fabric_token()
    if not token:
        return {"success": False, "error": "No auth token"}
        
    url = f"https://api.fabric.microsoft.com/v1/workspaces/{ALLOWED_WORKSPACE_ID}/items"
    headers = {"Authorization": f"Bearer {token}"}
    
    res = requests.get(url, headers=headers)
    if res.status_code == 200:
        return {"success": True, "items": res.json().get("value", [])}
    return {"success": False, "error": res.text}

if __name__ == "__main__":
    print(f"=== Fabric AI Engine (Workspace Lock: {ALLOWED_WORKSPACE_NAME}) ===")
    audit = list_workspace_items()
    if audit.get("success"):
        print(f"[AUDIT] Current items in {ALLOWED_WORKSPACE_NAME}: {len(audit['items'])}")
        for it in audit["items"][:5]:
            print(f"  - {it.get('displayName')} ({it.get('type')}) ID: {it.get('id')}")
    else:
        print(f"[AUDIT ERROR] {audit.get('error')}")
