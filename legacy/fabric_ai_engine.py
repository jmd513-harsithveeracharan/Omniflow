# --- SECURITY GUARDRAIL ---

class SecurityError(Exception):
    """Raised when an operation targets a workspace outside the allowed workspace."""
    pass

# Load config from app/config.py (which reads from .env and config.json)
try:
    from app.config import ALLOWED_WORKSPACE_ID, ALLOWED_WORKSPACE_NAME
except ImportError:
    # Fallback if app module not yet on path
    _CONFIG_FILE = os.path.join(os.path.dirname(__file__), "config.json")
    with open(_CONFIG_FILE, "r", encoding="utf-8") as _f:
        _cfg = json.load(_f)
    ALLOWED_WORKSPACE_ID   = os.getenv("FABRIC_ALLOWED_WORKSPACE_ID") or _cfg["ALLOWED_WORKSPACE_ID"]
    ALLOWED_WORKSPACE_NAME = os.getenv("FABRIC_ALLOWED_WORKSPACE_NAME") or _cfg.get("ALLOWED_WORKSPACE_NAME", "PBT_DATA_AGENT")

if not ALLOWED_WORKSPACE_ID:
    raise EnvironmentError("CRITICAL: ALLOWED_WORKSPACE_ID is not configured!")

print(f"[SECURITY LOCK ACTIVE] Engine locked to Workspace '{ALLOWED_WORKSPACE_NAME}' (ID: {ALLOWED_WORKSPACE_ID})")

# ALLOWED_WORKSPACE_ID and ALLOWED_WORKSPACE_NAME are now loaded above from app/config.py

def assert_workspace_security(target_ws_id: str):
    """Guarantees zero operations outside PBT_DATA_AGENT."""
    if target_ws_id != ALLOWED_WORKSPACE_ID:
        raise SecurityError(f"SECURITY BLOCK: Target workspace {target_ws_id} is NOT allowed! Restricted to {ALLOWED_WORKSPACE_NAME} ({ALLOWED_WORKSPACE_ID}) ONLY.")

def get_fabric_token():
    """Retrieves current Azure token. Delegates to app/auth.py for caching."""
    try:
        from app.auth import get_fabric_token as _cached_get
        return _cached_get()
    except ImportError:
        # Fallback: direct az CLI call (no caching)
        try:
            cmd = ["az", "account", "get-access-token", "--resource", "https://api.fabric.microsoft.com", "--query", "accessToken", "-o", "tsv"]
            result = subprocess.run(cmd, capture_output=True, text=True, check=True, shell=True)
            return result.stdout.strip()
        except Exception as e:
            print(f"[AUTH ERROR] Could not retrieve token: {e}")
            return None

