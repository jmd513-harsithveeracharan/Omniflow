import base64
import json
import requests

def create_fabric_notebook_item(workspace_id: str, access_token: str, notebook_name: str, pyspark_code: str):
    """
    Creates a Microsoft Fabric PySpark Notebook Item directly in a Workspace 
    using the Fabric Item Definition REST API (No Azure DevOps / Git needed!).
    """
    # 1. Format the PySpark code into standard Fabric Cell format
    fabric_notebook_content = f"""# FABRIC CELL 1
# MARKDOWN
# # {notebook_name}
# Generated automatically by AI Fabric Developer Platform

# FABRIC CELL 2
# PYSPARK
{pyspark_code}
"""

    # 2. Construct item.metadata.json
    item_metadata = {
        "type": "Notebook",
        "displayName": notebook_name,
        "description": "AI Generated Fabric PySpark Notebook"
    }

    # 3. Construct .platform settings
    platform_config = {
        "$schema": "https://developer.microsoft.com/json-schemas/fabric/gitIntegration/platformProperties/2.0.0/schema.json",
        "metadata": {
            "type": "Notebook",
            "displayName": notebook_name
        },
        "config": {
            "version": "2.0",
            "logicalId": "00000000-0000-0000-0000-000000000000"
        }
    }

    # 4. Convert all parts to Base64 (Required by Microsoft Fabric REST API)
    b64_notebook_content = base64.b64encode(fabric_notebook_content.encode('utf-8')).decode('utf-8')
    b64_item_metadata = base64.b64encode(json.dumps(item_metadata, indent=2).encode('utf-8')).decode('utf-8')
    b64_platform_config = base64.b64encode(json.dumps(platform_config, indent=2).encode('utf-8')).decode('utf-8')

    # 5. Construct the full Fabric Item Definition Payload
    payload = {
        "displayName": notebook_name,
        "type": "Notebook",
        "description": "Created automatically via AI Fabric REST API Engine",
        "definition": {
            "parts": [
                {
                    "path": "notebook-content.py",
                    "payload": b64_notebook_content,
                    "payloadType": "InlineBase64"
                },
                {
                    "path": "item.metadata.json",
                    "payload": b64_item_metadata,
                    "payloadType": "InlineBase64"
                },
                {
                    "path": ".platform",
                    "payload": b64_platform_config,
                    "payloadType": "InlineBase64"
                }
            ]
        }
    }

    # 6. Send POST request to Microsoft Fabric REST API Endpoint
    url = f"https://api.fabric.microsoft.com/v1/workspaces/{workspace_id}/items"
    headers = {
        "Authorization": f"Bearer {access_token}",
        "Content-Type": "application/json"
    }

    print(f"[DEPLOY] Deploying Fabric Notebook '{notebook_name}' to Workspace ID: {workspace_id}...")
    print(f"Endpoint URL: {url}\n")
    print("Item Payload Definition Preview:")
    print(json.dumps({"displayName": notebook_name, "type": "Notebook", "definition_parts_count": len(payload["definition"]["parts"])}, indent=2))

